import assert from 'node:assert/strict';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import ts from 'typescript';
await mkdir('.sites-runtime',{recursive:true});
await writeFile('.sites-runtime/check-recommendations.mjs',ts.transpileModule(await readFile('lib/recommendations.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {parseEngineProfile,mixRecommendations,recommendationSummary,PREFERENCE_TAGS}=await import('../.sites-runtime/check-recommendations.mjs');
const profile=(preferences)=>parseEngineProfile(JSON.stringify({version:1,source:'mpvpaper-engine',preferences}));
const nature=profile([{tag:'nature',weight:1}]);
const items=Array.from({length:12},(_,i)=>({id:String(i),category:i<8?'Nature':'Anime',tags:[i<8?'paysage':'anime']}));
const mix=mixRecommendations(items,nature);
assert.equal(mix.personalCount,6);assert.equal(mix.items.length,12);assert.equal(new Set(mix.items.map(i=>i.id)).size,12);
assert.deepEqual(mix.items.map(i=>mix.kinds.get(i.id)),Array.from({length:12},(_,i)=>i%2?'discovery':'personal'));
assert.deepEqual(mixRecommendations(items,null).items,items);
const sparse=mixRecommendations(items,profile([{tag:'anime',weight:1}]));
assert.equal(sparse.personalCount,4);assert.equal(sparse.items.length,12);assert.equal(sparse.target,6);
const unknown=mixRecommendations(items,profile([{tag:'espace',weight:1}]));assert.equal(unknown.personalCount,0);assert.deepEqual(unknown.items,items);
assert.equal(mixRecommendations(items.slice(0,5),nature).personalCount,2);
assert.equal(mixRecommendations(items.slice(0,1),nature).personalCount,0);
assert.equal(mixRecommendations([],nature).items.length,0);
assert.equal(mixRecommendations([...items,items[0]],nature).items.length,12);
assert.equal(mixRecommendations(items,profile([])).kinds.size,0);
const ranked=mixRecommendations([{id:'a',category:'Nature',tags:[]},{id:'b',category:'Nature',tags:['calme']},{id:'c',category:'Anime',tags:[]},{id:'d',category:'Ville',tags:[]}],profile([{tag:'nature',weight:.1},{tag:'calme',weight:1}]));
assert.equal(ranked.items[0].id,'b');
assert.throws(()=>parseEngineProfile('{'));
for(const bad of [{version:2,source:'mpvpaper-engine',preferences:[]},{version:1,source:'other',preferences:[]},{version:1,source:'mpvpaper-engine',preferences:[],paths:['/home/private']},null])assert.throws(()=>parseEngineProfile(JSON.stringify(bad)));
for(const weight of [0,2,-1,'1',true])assert.throws(()=>profile([{tag:'nature',weight}]));
assert.throws(()=>profile([{tag:'/home/private/file',weight:1}]));
assert.throws(()=>profile([{tag:'nature',weight:1},{tag:'nature',weight:.5}]));
assert.throws(()=>parseEngineProfile(' '.repeat(4097)));
assert.equal(PREFERENCE_TAGS.length,16);
// Optional profile generated by the real Python Engine exporter for both-side verification.
if(process.argv[2]){const exported=parseEngineProfile(await readFile(process.argv[2],'utf8'));const catalogue=JSON.parse(await readFile('data/catalog.json','utf8'));const actual=mixRecommendations(catalogue,exported);assert(actual.personalCount>0);assert.equal(actual.items.length,catalogue.length);}
console.log('Recommandations vérifiées : alternance 50/50, profils limités, filtres courts, repli, absence de doublons et contrat Engine.');

